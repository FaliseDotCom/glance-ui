import { readFile } from "node:fs/promises";
import fc from "fast-check";
import { describe, expect, it } from "vitest";
import { parse } from "yaml";
import { GLANCE_FILE_PATTERN, VALUE_PATTERN, parseDashboard, substitute, type DashboardT } from "@glance-editor/model";
import { generate } from "../src/index.ts";

const OPTS = { glanceVersion: "v0.8.6" };

async function sample(): Promise<DashboardT> {
  const json = JSON.parse(await readFile("test/fixtures/model/v2/sample.json", "utf8"));
  const { dashboard, issues } = parseDashboard(json);
  if (!dashboard) throw new Error(JSON.stringify(issues));
  return dashboard;
}

const withHtml = (source: string, title = "t"): DashboardT => ({
  schemaVersion: 2,
  pages: [{ _id: "p", name: "P", columns: [{ _id: "c", size: "full", widgets: [{ _id: "w", type: "html", title, source }] }] }],
});

describe("generate", () => {
  it.each([" \n", "a\n \nb", "trailing \nx", "\tx\n", "  indented\nfirst", "\n\n", "x\n", "\n \n${A}a", "a\u2028b\u0085c\ufeff", "#\n\n", "x\n\n\n"])("multi-line %j survives", (v) => {
    const { yaml } = generate(withHtml(v, v), OPTS);
    const w = parse(yaml).pages[0].columns[0].widgets[0];
    expect([w.source, w.title]).toEqual([v, v]);
  });

  it("is deterministic", async () => {
    const d = await sample();
    expect(generate(d, OPTS).yaml).toBe(generate(structuredClone(d), OPTS).yaml);
  });

  it("strips _id and writes the header (ADR-0010) without placeholders in comments", async () => {
    const { yaml } = generate(await sample(), OPTS);
    expect(yaml).not.toContain("_id");
    expect(yaml.startsWith("# Generated by Glance Editor for Glance v0.8.6.")).toBe(true);
    for (const line of yaml.split("\n").filter((l) => l.trimStart().startsWith("#"))) expect(line).not.toContain("${");
  });

  it("writes typed placeholders as plain scalars and records hints", async () => {
    const { yaml, placeholderHints } = generate(await sample(), OPTS);
    expect(yaml).toContain("limit: ${RSS_LIMIT}\n");
    expect(yaml).toContain("same-tab: ${SAME_TAB}\n");
    expect(placeholderHints.get("${RSS_LIMIT}")).toBe("number");
    expect(placeholderHints.get("${SAME_TAB}")).toBe("boolean");
  });

  it("turns array-shaped maps back into Glance maps", async () => {
    const out = parse(generate(await sample(), OPTS).yaml);
    expect(out.theme.presets.paper.light).toBe(true);
    const docker = out.pages[0].columns[2].widgets[0];
    expect(docker.containers.some_container).toEqual({ name: "Some Container", description: "Example override", hide: true });
  });

  it("writes every modelled widget's keys in field order", async () => {
    const { yaml } = generate(await sample(), OPTS);
    expect(yaml).toContain("- type: weather\n            location: Berlin, Germany\n            units: ${UNITS}\n            hour-format: 24h\n");
  });

  it("writes raw widgets back unchanged", async () => {
    const d = await sample();
    d.pages[0]!.columns[0]!.widgets.push({ _id: "raw", type: "from-the-future", _raw: { b: 1, a: { c: [2] } } });
    const out = parse(generate(d, OPTS).yaml);
    expect(out.pages[0].columns[0].widgets[3]).toEqual({ type: "from-the-future", b: 1, a: { c: [2] } });
  });

  it("encodes escapes so Glance sees exactly the intended placeholders", () => {
    const { yaml } = generate(withHtml("x: \\${NOT_A_VAR} ${LIVE}", "\\${E}${ADJ}\n "), OPTS);
    expect(yaml).toContain('source: "x: \\u0024{NOT_A_VAR} ${LIVE}"');
    expect(yaml).toContain('title: "\\u0024{E}\\u0024{ADJ}\\n "');
  });
});

// Property test: whatever string a user types (with placeholders anywhere), the YAML Glance ends up parsing
// (after its textual substitution) must contain exactly that string with placeholders replaced.
describe("placeholder round trip (property)", () => {
  const DUMMY = "glance-editor-placeholder";
  const token = fc.oneof(
    fc.constantFrom("${A_VAR}", "${secret:my_secret}", "${readFileFromEnv:TOKEN_FILE}", "\\${ESCAPED}", "${lower}", "${foo:BAR}"),
    fc.string({ unit: "binary", maxLength: 4 }),
    fc.constantFrom("$&", "$$", "$`", "$'", "\u2028", "\u0085", "\ufeff", "\r\n", "\t", "---", "...", "? ", "- "),
    fc.string({ unit: fc.constantFrom("a", " ", ":", "#", "'", '"', "\\", "\n", "-", "{", "}", "$", "[", "&", "*", "!", "%", "@", "`", "|", ">") , maxLength: 6 }),
  );
  const text = fc.array(token, { minLength: 1, maxLength: 8 }).map((parts) => parts.join(""));

  const resolve = () => DUMMY;
  /** What the user means: Glance's rule applied to the value on its own (VALUE_PATTERN). */
  const expected = (s: string) => substitute(s, resolve, { pattern: VALUE_PATTERN });
  /** What Glance actually does: its rule applied to the whole generated file. */
  const glance = (yaml: string) => substitute(yaml, resolve, { pattern: GLANCE_FILE_PATTERN });

  it("html source and title survive generate → Glance substitution → YAML parse", () => {
    fc.assert(
      fc.property(text, text, (source, title) => {
        const { yaml } = generate(withHtml(source, title), OPTS);
        const parsed = parse(glance(yaml));
        const w = parsed.pages[0].columns[0].widgets[0];
        expect(w.source).toBe(expected(source));
        expect(w.title).toBe(expected(title));
        expect(yaml).not.toContain(DUMMY);
      }),
      { numRuns: 5000 },
    );
  });
});
