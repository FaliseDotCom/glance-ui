import { existsSync, mkdirSync, readdirSync, readFileSync, statSync } from "node:fs";
import { dirname, join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import type { DashboardT, WidgetT } from "@glance-editor/model";
import { Editor } from "../src/index.ts";
import { open, setup, type Setup } from "./helpers.ts";

const COMMENTED = "test/fixtures/import/commented.yml";
const editors: Editor[] = [];
const track = async (s: Setup) => { const e = await open(s); editors.push(e); return e; };
afterEach(() => { while (editors.length) editors.pop()!.close(); });

const draftOf = async (e: Editor) => structuredClone((await e.state()).draft!);

describe("first run (D-34, D-35)", () => {
  it("with no file: first run, Start empty, first save creates version 1 with the generated header", async () => {
    const s = setup();
    mkdirSync(dirname(s.configPath), { recursive: true });
    const e = await track(s);
    expect(await e.state()).toMatchObject({ firstRun: true, liveExists: false, draft: null });
    await e.startEmpty("Home", "small-full-small");
    const d = await draftOf(e);
    expect(d.pages[0]!.columns.map((c) => c.size)).toEqual(["small", "full", "small"]);
    d.pages[0]!.columns[1]!.widgets.push({ _id: "w1", type: "clock" } as WidgetT);
    expect(e.setDraft(d).ok).toBe(true);
    const r = await e.save();
    expect(r).toMatchObject({ status: "saved", version: 1 });
    expect(s.live()).toMatch(/^# Generated by Glance Editor for Glance v0\.8\.6\./);
    expect(e.versions().map((v) => [v.number, v.source])).toEqual([[1, "editor"]]);
  });

  it("Start empty over an existing file keeps that file as version 0 on the first save", async () => {
    const s = setup("test/fixtures/valid/minimal.yml");
    const e = await track(s);
    const original = s.live();
    await e.startEmpty("New", "one-full");
    const d = await draftOf(e);
    d.pages[0]!.columns[0]!.widgets.push({ _id: "w1", type: "calendar" } as WidgetT);
    e.setDraft(d);
    expect(await e.save()).toMatchObject({ status: "saved", version: 1 });
    expect(await e.version(0)).toMatchObject({ source: "import", text: original });
  });

  it("import stores the file as version 0 and a no-edit save writes nothing", async () => {
    const s = setup(COMMENTED);
    const e = await track(s);
    const r = await e.importLive();
    expect(r.ok).toBe(true);
    expect(e.versions()).toMatchObject([{ number: 0, source: "import", live: true }]);
    expect((await e.state()).changes).toEqual([]);
    expect(await e.save()).toEqual({ status: "nothing" });
  });
});

describe("save pipeline (handoff §4)", () => {
  async function imported(seed = COMMENTED, extra = {}) {
    const s = setup(seed, extra);
    const e = await track(s);
    await e.importLive();
    return { s, e };
  }

  it("saves an edit into the file in place, keeps .prev, records the change, continues the draft", async () => {
    const { s, e } = await imported();
    const before = s.live();
    const d = await draftOf(e);
    d.pages[0]!.name = "Start";
    expect(e.setDraft(d)).toMatchObject({ ok: true, changes: [{ kind: "renamed", label: 'Page "Home" → "Start"' }] });
    const r = await e.save();
    expect(r).toMatchObject({ status: "saved", version: 1, reload: "not-checked", warnings: [] });
    expect(s.live()).toBe(before.replace("  - name: Home # shown first", "  - name: Start # shown first"));
    expect(readFileSync(`${s.configPath}.prev`, "utf8")).toBe(before);
    expect(readdirSync(dirname(s.configPath)).filter((f) => f.endsWith(".tmp"))).toEqual([]);
    expect(await e.version(1)).toMatchObject({ source: "editor", live: true, changes: [{ kind: "renamed" }] });
    expect((await e.state()).changes).toEqual([]);
  });

  it("editor rule errors: nothing written, problems point at the page", async () => {
    const { s, e } = await imported();
    const before = s.live();
    const d = await draftOf(e);
    const cols = d.pages[0]!.columns;
    cols.push({ _id: "c3", size: "small", widgets: [] }, { _id: "c4", size: "small", widgets: [] });
    e.setDraft(d);
    const r = await e.save();
    expect(r.status).toBe("problems");
    if (r.status === "problems") expect(r.problems[0]).toMatchObject({ source: "editor", code: "page.too-many-columns", location: { pageId: d.pages[0]!._id } });
    expect(s.live()).toBe(before);
    expect(e.versions()).toHaveLength(1);
  });

  it("Glance rejects (editor rules pass): Glance's own text, nothing written", async () => {
    const { s, e } = await imported("test/fixtures/valid/minimal.yml");
    const before = s.live();
    const d = await draftOf(e);
    d.pages[0]!.columns[0]!.widgets.push({ _id: "w-bad", type: "clock", "hour-format": "24h", timezones: [{ _id: "tz", timezone: "Not/AZone" }] } as WidgetT);
    e.setDraft(d);
    const r = await e.save();
    expect(r.status).toBe("problems");
    if (r.status === "problems") expect(r.problems[0]).toMatchObject({ source: "glance", code: "glance.config-validate" });
    if (r.status === "problems") expect(r.problems[0]!.message).toMatch(/timezone/i);
    expect(s.live()).toBe(before);
  });

  it("validator can't run: nothing written (D-27)", async () => {
    const { s, e: first } = await imported("test/fixtures/valid/minimal.yml");
    first.close();
    editors.splice(editors.indexOf(first), 1);
    const e = await track({ ...s, cfg: { ...s.cfg, glanceBin: "/nonexistent/glance" } });
    const before = s.live();
    const d = await draftOf(e);
    d.pages[0]!.name = "X";
    e.setDraft(d);
    const r = await e.save();
    expect(r).toMatchObject({ status: "problems", problems: [{ code: "glance.unavailable" }] });
    expect(s.live()).toBe(before);
    expect(e.versions()).toHaveLength(1);
  });

  it("changed outside the editor: outside version stored first, then keep-draft or load-file (D-32)", async () => {
    const { s, e } = await imported();
    const d = await draftOf(e);
    d.pages[0]!.name = "From the draft";
    e.setDraft(d);
    s.write(s.live().replace("name: Second", "name: Edited by hand"));
    expect((await e.state()).changedOutside).toBe(true);

    const r1 = await e.save();
    expect(r1).toEqual({ status: "conflict", outsideVersion: 1 });
    expect(await e.version(1)).toMatchObject({ source: "outside", live: true });
    expect(s.live()).toContain("Edited by hand");
    expect(await e.save()).toEqual({ status: "conflict", outsideVersion: 1 }); // asking twice doesn't duplicate it
    expect(e.versions()).toHaveLength(2);

    const r2 = await e.save({ acceptOutside: 1 }); // keep the draft
    expect(r2).toMatchObject({ status: "saved", version: 2 });
    expect(s.live()).toContain("From the draft");
    expect(s.live()).not.toContain("Edited by hand");

    s.write(s.live().replace("name: Second", "name: Hand again"));
    await e.discard(); // load the file instead
    expect((await e.state()).draft!.pages[1]!.name).toBe("Hand again");
    expect(e.versions()[0]).toMatchObject({ number: 3, source: "outside" });
  });

  it("an edit made while the editor was stopped is recorded at start (handoff §5)", async () => {
    const { s, e } = await imported();
    e.close();
    editors.pop();
    s.write(s.live() + "\n# hand edit\n");
    const e2 = await track(s);
    expect(e2.versions()[0]).toMatchObject({ number: 1, source: "outside", live: true });
  });
});

describe("restore and discard (D-31, D-33)", () => {
  it("restore loads a version into the draft and never writes; Save makes it a new version", async () => {
    const s = setup(COMMENTED);
    const e = await track(s);
    await e.importLive();
    const d = await draftOf(e);
    d.pages.pop();
    e.setDraft(d);
    await e.save(); // version 1: second page removed
    const afterSave = s.live();
    const mtime = statSync(s.configPath).mtimeMs;

    const st = await e.restore(0);
    expect(st.draft!.pages.map((p) => p.name)).toEqual(["Home", "Second"]);
    expect(st.changes).toEqual([expect.objectContaining({ kind: "added", label: 'Page "Second"' })]); // vs the live file
    expect(s.live()).toBe(afterSave);
    expect(statSync(s.configPath).mtimeMs).toBe(mtime);

    expect(await e.save()).toMatchObject({ status: "saved", version: 2 });
    expect(s.live()).toBe(readFileSync(COMMENTED, "utf8")); // spliced back to the original, comments and all
  });

  it("restores a version that contains $include lines (resolved next to the live file)", async () => {
    const s = setup("test/fixtures/import/includes/");
    const e = await track(s);
    await e.importLive();
    expect((await e.version(0))!.text).toContain("$include: home.yml");
    const d = await draftOf(e);
    d.pages[0]!.name = "Changed";
    e.setDraft(d);
    await e.save();
    expect(s.live()).not.toContain("include:"); // D-36: merged on first save
    const st = await e.restore(0);
    expect(st.draft!.pages.map((p) => p.name)).toEqual(["Home", "Other"]);
    expect(readdirSync(dirname(s.configPath)).filter((f) => f.startsWith(".glance-editor-restore"))).toEqual([]);
  });

  it("discard resets the draft to the live file", async () => {
    const s = setup(COMMENTED);
    const e = await track(s);
    await e.importLive();
    const d = await draftOf(e);
    d.pages[0]!.name = "Temp";
    e.setDraft(d);
    expect((await e.state()).changes).toHaveLength(1);
    expect((await e.discard()).changes).toEqual([]);
  });
});

describe("drafts", () => {
  it("are stored on the server (survive a restart, D-46)", async () => {
    const s = setup(COMMENTED);
    const e = await track(s);
    await e.importLive();
    const d = await draftOf(e);
    d.pages[0]!.name = "Phone edit";
    e.setDraft(d);
    e.close();
    editors.pop();
    const e2 = await track(s);
    expect((await e2.state()).draft!.pages[0]!.name).toBe("Phone edit");
  });

  it("refuse a malformed model and keep the previous draft", async () => {
    const s = setup(COMMENTED);
    const e = await track(s);
    await e.importLive();
    const r = e.setDraft({ schemaVersion: 2, pages: [{ name: "no id" }] });
    expect(r.ok).toBe(false);
    expect((await e.state()).draft!.pages[0]!.name).toBe("Home");
  });

  it("report every kind of change (design §2: a structural diff)", async () => {
    const s = setup(COMMENTED);
    const e = await track(s);
    await e.importLive();
    const d = await draftOf(e) as DashboardT;
    const home = d.pages[0]!;
    const [weather] = home.columns[1]!.widgets.splice(2, 1);
    d.pages[1]!.columns[0]!.widgets.push(weather!);
    home.columns[0]!.widgets.reverse();
    home.columns[1]!.widgets.push({ _id: "n1", type: "html", source: "x" } as WidgetT);
    d.theme!["primary-color"] = "1 2 3";
    const kinds = e.setDraft(d).ok && (await e.state()).changes.map((c) => `${c.kind}:${c.label}`);
    expect(kinds).toEqual(expect.arrayContaining([
      "moved:Widget weather", "added:Widget html", "changed:Theme", expect.stringMatching(/^moved:Widgets reordered/),
    ]));
  });
});

describe("storage (ADR-0002, ADR-0003, ADR-0008)", () => {
  it("refuses a database newer than the code", async () => {
    const s = setup(COMMENTED);
    const e = await track(s);
    e.close();
    editors.pop();
    const { DatabaseSync } = await import("node:sqlite");
    const raw = new DatabaseSync(join(s.dataDir, "editor.sqlite"));
    raw.exec("PRAGMA user_version = 99");
    raw.close();
    await expect(Editor.open(s.cfg)).rejects.toThrow(/newer than this editor/);
  });

  it("daily backups keep the newest 14", async () => {
    let t = Date.UTC(2026, 9, 1);
    const s = setup(COMMENTED, { now: () => new Date((t += 86_400_000)) });
    const e = await track(s);
    for (let i = 0; i < 16; i++) e.dailyBackup();
    const files = readdirSync(join(s.dataDir, "backups"));
    expect(files).toHaveLength(14);
    expect(existsSync(join(s.dataDir, "backups", files.sort()[13]!))).toBe(true);
  });
});
