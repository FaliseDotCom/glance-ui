// Extracts facts from Glance's source at the pinned commit (glance.version) into
// packages/model/src/glance-source.generated.ts:
//   - the widget types `newWidget` accepts (internal/glance/widget.go), so a test fails if a schema is missing;
//   - the built-in theme list (docs/themes.md), for the theme gallery's swatches.
// Only names and numeric colour values are taken (facts, not Glance's code or prose).
//
// Usage: node scripts/glance-source-data.ts           write the file
//        node scripts/glance-source-data.ts --check   fail if the checked-in file differs (run by scripts/test.sh)

import { readFileSync, writeFileSync } from "node:fs";
import { parse } from "yaml";

const OUT = "packages/model/src/glance-source.generated.ts";

const pin = Object.fromEntries(
  readFileSync("glance.version", "utf8").split("\n").filter((l) => /^[A-Z_]+=/.test(l)).map((l) => l.split(/=(.*)/s).slice(0, 2)),
) as Record<string, string>;
const { GLANCE_VERSION: version, GLANCE_COMMIT: commit } = pin;
if (!version || !commit) throw new Error("glance.version: GLANCE_VERSION or GLANCE_COMMIT missing");

async function fetchSource(path: string): Promise<string> {
  const url = `https://raw.githubusercontent.com/glanceapp/glance/${commit}/${path}`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.text();
}

function widgetTypes(go: string): string[] {
  const body = /func newWidget\(widgetType string\)[\s\S]*?\n\tswitch widgetType \{([\s\S]*?)\n\tdefault:/.exec(go)?.[1];
  if (!body) throw new Error("widget.go: newWidget switch not found");
  const types = [...body.matchAll(/^\tcase (.+):$/gm)].flatMap((m) => [...m[1]!.matchAll(/"([a-z0-9-]+)"/g)].map((x) => x[1]!));
  if (types.length < 20) throw new Error(`widget.go: only ${types.length} types found`);
  return types;
}

interface Theme {
  name: string;
  light: boolean;
  properties: Record<string, string | number | boolean>;
}

function themes(md: string): Theme[] {
  const out: Theme[] = [];
  let section = "";
  let name = "";
  const lines = md.split("\n");
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i]!;
    if (line.startsWith("## ")) section = line.slice(3).trim();
    else if (line.startsWith("### ")) name = line.slice(4).trim();
    else if (line.trim() === "```yaml" && name) {
      const end = lines.indexOf("```", i + 1);
      const doc = parse(lines.slice(i + 1, end).join("\n")) as { theme?: Record<string, string | number | boolean> };
      if (!doc?.theme) throw new Error(`themes.md: "${name}" has no theme block`);
      // Colours stay strings ("225 14 15"); multipliers stay numbers, as written.
      const properties = Object.fromEntries(Object.entries(doc.theme).map(([k, v]) => [k, typeof v === "number" && /color/.test(k) ? String(v) : v]));
      const light = properties.light === true;
      if (light !== (section === "Light")) throw new Error(`themes.md: "${name}" is under ${section} but light=${light}`);
      out.push({ name, light, properties });
      name = "";
      i = end;
    }
  }
  return out;
}

const [widgetGo, themesMd] = await Promise.all([fetchSource("internal/glance/widget.go"), fetchSource("docs/themes.md")]);
const text = `// Generated by scripts/glance-source-data.ts from glanceapp/glance@${commit} (${version}). Do not edit.
// Facts only: the widget type names Glance's newWidget accepts (internal/glance/widget.go) and the built-in themes'
// names and values (docs/themes.md).

/** Widget types Glance ${version} accepts, in its source order. */
export const GLANCE_SOURCE_WIDGET_TYPES: readonly string[] = ${JSON.stringify(widgetTypes(widgetGo), null, 2)};

export interface GlanceTheme {
  name: string;
  light: boolean;
  /** The theme's keys exactly as docs/themes.md writes them (colours are "H S L" strings). */
  properties: Readonly<Record<string, string | number | boolean>>;
}

/** The themes in Glance ${version}'s docs/themes.md, in its order (dark first). */
export const GLANCE_THEMES: readonly GlanceTheme[] = ${JSON.stringify(themes(themesMd), null, 2)};
`;

if (process.argv.includes("--check")) {
  const current = readFileSync(OUT, "utf8");
  if (current !== text) {
    console.error(`${OUT} is out of date with Glance ${version}. Run: node scripts/glance-source-data.ts`);
    process.exit(1);
  }
  console.log(`${OUT} matches glanceapp/glance@${commit.slice(0, 7)}`);
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT}`);
}
