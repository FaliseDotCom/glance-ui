import { readFileSync } from "node:fs";
import type { Page } from "@playwright/test";
import { expect, expectAccessible, expectTargets, fixture, isPhone, test } from "./fixtures.ts";
import { shot } from "./shots.ts";

async function importSeed(page: Page, url: string) {
  await page.goto(url);
  await page.getByRole("button", { name: /Import glance\.yml/ }).click();
  await expect(page.getByRole("heading", { name: "Ready to import" })).toBeVisible();
  await page.getByRole("button", { name: /^Import \d+ pages?$/ }).click();
  await expect(page.getByLabel("Page name")).toBeVisible();
}

async function save(page: Page) {
  await page.getByRole("button", { name: "Save", exact: true }).click();
  const review = page.getByRole("dialog", { name: "Review and save" });
  await expect(review).toBeVisible();
  await review.getByRole("button", { name: "Check and save" }).click();
}

const column = (page: Page, n: number) => page.getByRole("region", { name: `Column ${n}`, exact: true });

test.describe("Flow 1: create a dashboard from scratch", () => {
  test("no file: Start empty, pick a layout, save version 1", async ({ page, editor }) => {
    await page.goto(editor.url);
    await expect(page.getByRole("heading", { name: "Set up the editor" })).toBeVisible();
    // noFile: Import is disabled and says why (design 03).
    await expect(page.getByRole("button", { name: /Import glance\.yml/ })).toBeDisabled();
    await expect(page.getByText("No glance.yml found at the mounted path.")).toBeVisible();
    await expectAccessible(page, "welcome");
    await expectTargets(page, "welcome");
    await shot(page, "first-run");

    await page.getByRole("button", { name: /Start empty/ }).click();
    await page.getByLabel("Page name").fill("Home");
    await page.getByRole("button", { name: "Small + full + small" }).click();
    await expect(page.getByRole("button", { name: "Small + full + small" })).toHaveAttribute("aria-pressed", "true");
    await expectAccessible(page, "layout pick");
    await expectTargets(page, "layout pick");
    await shot(page, "start-empty");
    await page.getByRole("button", { name: "Create page" }).click();

    await expect(page.getByLabel("Page name")).toHaveValue("Home");
    await expect(page.getByRole("region", { name: /^Column \d$/ })).toHaveCount(3);
    await expect(column(page, 2).getByText("No widgets in this column yet.")).toBeVisible();
    await expectAccessible(page, "page editor");
    await expectTargets(page, "page editor");
    await shot(page, "page-editor-new");

    await save(page);
    await expect(page.getByRole("heading", { name: "Version 1 is written" })).toBeVisible();
    await shot(page, "saved");
    expect(editor.live()).toMatch(/^# Generated by Glance Editor/);
    expect(editor.live()).toContain("name: Home");
    await page.getByRole("button", { name: "View history" }).click();
    await expect(page.getByRole("heading", { name: "History" })).toBeVisible();
    await expect(page.getByRole("button", { name: /Version 1/ })).toBeVisible();
    await expectAccessible(page, "history");
  });
});

test.describe("Flow 2: edit a page layout", () => {
  test.use({ opts: { seed: fixture("home.yml"), glance: true } });

  test("rules by disabling, remove a column with Undo, slim, sizes, reorder, rename, save live", async ({ page, editor }) => {
    await importSeed(page, editor.url);
    await expect(page.locator(".status")).toHaveAttribute("title", "Glance reachable");

    // 1. Slim is disabled, with the reason under it (3 columns).
    await expect(page.getByRole("button", { name: "Slim" })).toBeDisabled();
    await expect(page.getByText("Slim allows at most 2 columns. Remove a column to use it.")).toBeVisible();
    await expect(page.getByRole("button", { name: "Add column" })).toBeDisabled();
    await expect(page.getByText("A page holds at most 3 columns.")).toBeVisible();
    await expect(page.getByRole("button", { name: "Remove column 2" })).toBeDisabled(); // the only full column
    await shot(page, "page-editor-imported");

    // 2. Column 3 → ×: its widget moves into column 2, and the toast offers Undo.
    await page.getByRole("button", { name: "Remove column 3" }).click();
    await expect(page.getByText("Column removed. Its 1 widget moved to column 2.")).toBeVisible();
    await expect(column(page, 2).locator(".wname", { hasText: "To-do" })).toBeVisible();
    await shot(page, "undo-toast");
    await page.getByRole("button", { name: "Undo" }).click();
    await expect(page.getByRole("region", { name: /^Column \d$/ })).toHaveCount(3);
    await expect(column(page, 3).locator(".wname", { hasText: "To-do" })).toBeVisible();
    await page.getByRole("button", { name: "Remove column 3" }).click();
    await expect(page.getByRole("region", { name: /^Column \d$/ })).toHaveCount(2);

    // 3. Slim is now available; with it, Add column disables with its reason.
    await page.getByRole("button", { name: "Slim" }).click();
    await expect(page.getByRole("button", { name: "Slim" })).toHaveAttribute("aria-pressed", "true");
    await expect(page.getByRole("button", { name: "Add column" })).toBeDisabled();
    await expect(page.getByText("Slim pages allow at most 2 columns.")).toBeVisible();

    // 4. Column 1 → Full. Column 2's Small option stays available.
    await column(page, 1).getByRole("button", { name: "Full" }).click();
    await expect(column(page, 1).getByRole("button", { name: "Full" })).toHaveAttribute("aria-pressed", "true");
    await expect(column(page, 2).getByRole("button", { name: "Small · 300 px" })).toBeEnabled();

    // 5. Reorder columns with the grip's move buttons; rename the page and set a slug.
    await column(page, 1).getByRole("button", { name: "Move column 1", exact: true }).click();
    await column(page, 1).getByRole("button", { name: isPhone(page) ? "Move down" : "Move right" }).click();
    await expect(column(page, 2).locator(".wname", { hasText: "Clock" })).toBeVisible();
    await page.getByLabel("Page name").fill("Start");
    await page.getByLabel("Slug").fill("start");
    await expectAccessible(page, "page editor after edits");
    await expectTargets(page, "page editor after edits");

    await page.getByRole("button", { name: "Save", exact: true }).click();
    await expect(page.getByRole("dialog", { name: "Review and save" }).getByText('Renamed: Page "Home" → "Start"')).toBeVisible();
    await shot(page, "review");
    await expectAccessible(page, "review sheet");
    await page.getByRole("button", { name: "Check and save" }).click();
    // D-29: Glance's reload signal changed, so the version is live.
    await expect(page.getByRole("heading", { name: "Version 1 is live" })).toBeVisible();
    const live = editor.live();
    expect(live).toContain("name: Start");
    expect(live).toContain("width: slim");
    expect(live).toContain("title: Services # kept next to its value"); // D-38
    expect(live).not.toContain("type: to-do\n      - size: small"); // column 3 is gone
  });
});

test.describe("Flow 6: save → validation error → fix", () => {
  test.use({ opts: { seed: fixture("home.yml"), glance: true } });

  test("an empty page name blocks Save; Go to points at it; fixing it clears the banner", async ({ page, editor }) => {
    await importSeed(page, editor.url);
    const before = editor.live();
    await page.getByLabel("Page name").fill("");
    await expect(page.getByText("Glance needs a page name.")).toBeVisible();
    await save(page);
    const problems = page.getByRole("dialog", { name: "Problems" });
    await expect(problems.getByRole("heading", { name: "1 problem found" })).toBeVisible();
    await expect(problems.getByText("glance.yml is unchanged and Glance keeps running the live version.")).toBeVisible();
    await expect(problems.getByText("Editor check · Untitled page")).toBeVisible();
    await shot(page, "problems");
    await expectAccessible(page, "problems sheet");
    expect(editor.live()).toBe(before);

    await problems.getByRole("button", { name: "Go to" }).click();
    await expect(page.getByLabel("Page name")).toBeFocused();
    await expect(page.locator(".field.hl")).toBeVisible();
    await expect(page.getByText("1 problem to fix before saving.")).toBeVisible();
    await shot(page, "problem-banner");

    await page.getByLabel("Page name").fill("Home again");
    await expect(page.getByText("1 problem to fix before saving.")).toBeHidden();
    await save(page);
    await expect(page.getByRole("heading", { name: "Version 1 is live" })).toBeVisible();
    expect(editor.live()).toContain("name: Home again");
  });

  test("Glance rejects what the editor's checks pass: Glance's message verbatim, the widget gets a Fix badge", async ({ page, editor }) => {
    await importSeed(page, editor.url);
    // A widget the Phase 6 inspector will edit; here it is put into the draft through the API.
    const state = await (await page.request.get(`${editor.url}/api/state`)).json();
    state.draft.pages[1].columns[0].widgets.push({ _id: "bad-template", type: "custom-api", title: "Status", template: "{{ .JSON" });
    const put = await page.request.put(`${editor.url}/api/draft`, { data: state.draft, headers: { origin: editor.url } });
    expect((await put.json()).ok).toBe(true);
    await page.reload();
    await save(page);
    const problems = page.getByRole("dialog", { name: "Problems" });
    await expect(problems.getByText(/Glance config:validate · Ops › Column 1 › Status/)).toBeVisible();
    await expect(problems.getByText(/parsing template/)).toBeVisible();
    await problems.getByRole("button", { name: "Go to" }).click();
    await expect(page.getByLabel("Page name")).toHaveValue("Ops");
    await expect(page.locator(".wcard.hl", { hasText: "Status" }).getByText("Fix")).toBeVisible();
    // Design 03 "Save blocked by Glance": Go to opens the widget's YAML tab. Fix it there, apply, save.
    const ins = page.getByRole("complementary", { name: "Widget settings" });
    await expect(ins.getByRole("tab", { name: "YAML" })).toHaveAttribute("aria-selected", "true");
    const box = ins.getByLabel("YAML for this widget");
    await expect(box).toHaveValue("type: custom-api\ntitle: Status\ntemplate: \"{{ .JSON\"\n");
    await shot(page, "glance-rejects");
    await box.fill("type: custom-api\ntitle: Status\ntemplate: <p>{{ .JSON.String \"status\" }}</p>\n");
    await ins.getByRole("button", { name: "Apply YAML" }).click();
    await ins.getByRole("button", { name: isPhone(page) ? "Back to layout" : "Close settings" }).click();
    await save(page);
    await expect(page.getByRole("heading", { name: "Version 1 is live" })).toBeVisible();
    expect(editor.live()).toContain("          - type: custom-api\n            title: Status\n            template: <p>{{ .JSON.String \"status\" }}</p>\n");
  });
});

test.describe("Flow 7: roll back", () => {
  test.use({ opts: { seed: fixture("home.yml"), glance: true } });

  test("an outside edit becomes its own version; restore version 1 as the draft; saving makes it the newest", async ({ page, editor }) => {
    await importSeed(page, editor.url);
    await page.getByLabel("Page name").fill("Version one");
    await save(page);
    await expect(page.getByRole("heading", { name: "Version 1 is live" })).toBeVisible();
    await page.getByRole("button", { name: "Done" }).click();
    const v1 = editor.live();

    // Someone edits glance.yml by hand; opening the editor records it (design 03).
    await new Promise((r) => setTimeout(r, 1100)); // Glance's reload stamp has 1 s resolution
    editor.write(v1.replace("name: Version one", "name: Edited by hand"));
    await page.reload();
    await (isPhone(page) ? page.getByRole("navigation", { name: "Sections" }) : page.getByRole("navigation", { name: "Editor" })).getByRole("button", { name: /History/ }).click();
    await expect(page.getByRole("button", { name: /Version 2/ }).locator(".pill", { hasText: "Outside editor" })).toBeVisible();

    await page.getByRole("button", { name: /Version 1/ }).click();
    await expect(page.getByLabel("Lines that differ")).toContainText("+   - name: Version one");
    await expect(page.getByLabel("Lines that differ")).toContainText("-   - name: Edited by hand");
    await shot(page, "history");
    await expectAccessible(page, "history detail");
    await expectTargets(page, "history detail");
    await page.getByRole("button", { name: "Restore as draft" }).click();
    await expect(page.getByText("Version 1 loaded as the draft. Save to make it live.")).toBeVisible();
    await expect(page.getByLabel("Page name")).toHaveValue("Version one");
    expect(editor.live()).toContain("name: Edited by hand"); // restore never writes (D-31)

    // Glance's reload stamp has 1 s resolution (ADR-0009): a reload in the same second as the hand edit's can't be told apart.
    await new Promise((r) => setTimeout(r, 1100));
    await page.getByRole("button", { name: "Save", exact: true }).click();
    await expect(page.getByRole("dialog", { name: "Review and save" }).getByText("Restored version 1 as the draft")).toBeVisible();
    await page.getByRole("button", { name: "Check and save" }).click();
    await expect(page.getByRole("heading", { name: "Version 3 is live" })).toBeVisible();
    expect(editor.live()).toBe(v1);
    expect(readFileSync(editor.configPath, "utf8")).toBe(v1);
  });
});
